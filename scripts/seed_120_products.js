async function seedMore() {
  const connection = await mysql.createConnection(dbConfig);
  console.log(`Connected to MySQL: ${dbConfig.database}`);

  try {
    let added = 0;
    for (const p of extraProducts) {
      const [existing] = await connection.query('SELECT id FROM products WHERE slug = ?', [p.slug]);
      if (existing.length === 0) {
        const [res] = await connection.query(
          `INSERT INTO products (name, slug, category, gender, price, discount_price, rating, reviews_count, badge, featured, trending, description, material, origin, color_name, color_hex, stock)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [
            p.name,
            p.slug,
            p.category,
            p.gender,
            p.price,
            p.discount_price,
            p.rating,
            p.reviews_count,
            p.badge,
            p.featured,
            p.trending,
            p.description,
            p.material,
            p.origin,
            p.color_name,
            p.color_hex,
            p.stock
          ]
        );
        const productId = res.insertId;
        added++;

        for (let idx = 0; idx < p.images.length; idx++) {
          await connection.query(
            'INSERT INTO product_images (product_id, image_url, is_primary) VALUES (?, ?, ?)',
            [productId, p.images[idx], idx === 0 ? 1 : 0]
          );
        }

        const sizes = p.gender === 'Women' ? ['5', '6', '7', '8', '9', '10'] : ['7', '8', '9', '10', '11', '12'];
        for (const s of sizes) {
          await connection.query(
            'INSERT INTO product_sizes (product_id, size, stock) VALUES (?, ?, ?)',
            [productId, s, 15]
          );
        }
      }
    }

    console.log(`✓ Added ${added} new targeted products for perfect balance!`);

    // Verification check for Women + Formal
    const [wf] = await connection.query(
      `SELECT COUNT(*) as count FROM products WHERE category = 'Formal' AND (gender = 'Women' OR gender = 'Unisex')`
    );
    console.log(`✓ Total products matching "Women + Formal": ${wf[0].count} (Target: >= 15)`);

    // Verification for each category
    const [cats] = await connection.query(
      `SELECT category, COUNT(*) as count FROM products GROUP BY category ORDER BY category`
    );
    console.table(cats);

    const [[tot]] = await connection.query('SELECT COUNT(*) as count FROM products');
    console.log(`🎉 GRAND TOTAL IN DB: ${tot.count} PRODUCTS!`);

  } catch (e) {
    console.error('Error:', e);
  } finally {
    await connection.end();
  }
}

