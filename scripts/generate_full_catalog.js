async function seed80() {
  const connection = await mysql.createConnection(dbConfig);
  console.log(`Connected to MySQL: ${dbConfig.database}`);

  try {
    console.log('Synchronizing 80 products catalog...');

    for (const p of catalog80) {
      const [existing] = await connection.query('SELECT id FROM products WHERE slug = ?', [p.slug]);
      let productId = existing[0]?.id;

      if (!productId) {
        const [insertRes] = await connection.query(
          `INSERT INTO products (name, slug, category, gender, price, discount_price, rating, reviews_count, badge, featured, trending, description, material, origin, color_name, color_hex, stock)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [
            p.name,
            p.slug,
            p.category,
            p.gender,
            p.price,
            p.discount_price,
            p.rating,
            p.reviews_count,
            p.badge,
            p.featured,
            p.trending,
            p.description,
            p.material,
            p.origin,
            p.color_name,
            p.color_hex,
            p.stock
          ]
        );
        productId = insertRes.insertId;

        // Insert gallery images
        for (let idx = 0; idx < p.images.length; idx++) {
          await connection.query(
            'INSERT INTO product_images (product_id, image_url, is_primary) VALUES (?, ?, ?)',
            [productId, p.images[idx], idx === 0 ? 1 : 0]
          );
        }

        // Insert sizes
        const defaultSizes = p.gender === 'Women' ? ['5', '6', '7', '8', '9', '10'] : ['7', '8', '9', '10', '11', '12'];
        for (const size of defaultSizes) {
          await connection.query(
            'INSERT INTO product_sizes (product_id, size, stock) VALUES (?, ?, ?)',
            [productId, size, 15]
          );
        }
      } else {
        // Update product to ensure correct category and gender
        await connection.query(
          `UPDATE products SET category = ?, gender = ?, price = ?, discount_price = ?, badge = ?, featured = ?, trending = ?, description = ?
           WHERE id = ?`,
          [p.category, p.gender, p.price, p.discount_price, p.badge, p.featured, p.trending, p.description, productId]
        );

        // Check if images exist, if not insert
        const [imgRows] = await connection.query('SELECT id FROM product_images WHERE product_id = ?', [productId]);
        if (imgRows.length === 0) {
          for (let idx = 0; idx < p.images.length; idx++) {
            await connection.query(
              'INSERT INTO product_images (product_id, image_url, is_primary) VALUES (?, ?, ?)',
              [productId, p.images[idx], idx === 0 ? 1 : 0]
            );
          }
        }
      }
    }

    // Print breakdown
    const [breakdown] = await connection.query(
      `SELECT category, gender, COUNT(*) as count FROM products GROUP BY category, gender ORDER BY category, gender`
    );
    console.log('\n--- CATALOG BREAKDOWN IN DATABASE ---');
    console.table(breakdown);

    const [categoryTotals] = await connection.query(
      `SELECT category, COUNT(*) as total FROM products GROUP BY category ORDER BY category`
    );
    console.log('\n--- TOTALS PER CATEGORY (Target: min 16 each) ---');
    console.table(categoryTotals);

    const [genderTotals] = await connection.query(
      `SELECT gender, COUNT(*) as total FROM products GROUP BY gender ORDER BY gender`
    );
    console.log('\n--- TOTALS PER GENDER ---');
    console.table(genderTotals);

    const [[overall]] = await connection.query('SELECT COUNT(*) as total FROM products');
    console.log(`\n🎉 TOTAL PRODUCTS IN DB: ${overall.total}`);

  } catch (err) {
    console.error('Error seeding 80 products:', err);
  } finally {
    await connection.end();
  }
}

seed80();
